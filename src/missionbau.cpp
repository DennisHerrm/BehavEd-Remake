std::string klein(std::string s) {
    for (char& c : s) { c = static_cast<char>(std::tolower(static_cast<unsigned char>(c))); }
    return s;
}

// Diese Namen nimmt die Engine statt eines Skripts (NPC_spawn.cpp,
// BSTATE_STRINGS in Q3_Interface): "deathscript" "idle" startet kein Skript.
bool istVerhaltensName(const std::string& v) {
    static const std::set<std::string> kNamen = {
        "default", "idle", "roam", "walk", "run", "standshoot", "standguard", "patrol", "huntkill",
        "evade", "evadeshoot", "runshoot", "defend", "snipe", "combat", "medic", "takecover",
        "getammo", "advancefight", "face", "wait", "investigate", "follow_leader", "sleep",
        "flee", "cinematic", "jump", "search", "noclip", "remove", "shoot"};
    return v.find('/') == std::string::npos && kNamen.count(klein(v)) != 0;
}

std::string zahl(float v) {
    char b[32];
    std::snprintf(b, sizeof(b), "%.3f", static_cast<double>(v));
    return b;
}

