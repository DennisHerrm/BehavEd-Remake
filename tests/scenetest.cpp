    // g_weapon.cpp:449 ff.), und fuer WP_BLASTER auf einem NPC:
    //
    //     muzzlePoint[2] += viewheight;   // 36
    //     muzzlePoint[2] -= 1;
    //     VectorMA( muzzlePoint, 2, forward, muzzlePoint );
    //     VectorMA( muzzlePoint, 1, right,   muzzlePoint );
    //
