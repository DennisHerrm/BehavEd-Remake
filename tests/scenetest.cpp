        // ohne dass es bei Gierwinkel 0 auffiele.
        bhed::muzzlePoint(o, 90.0F, "WP_BLASTER", m);
        expect("gedreht wandert vorn auf +y", near(m[1], 202.0F, 0.01F));
        expect("und rechts auf +x", near(m[0], 101.0F, 0.01F));

