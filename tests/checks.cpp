        //
        // Nur fuer die gepunkteten Linien: dort hoert die Senkrechte auf
        // halber Hoehe auf. Geprueft wird die Regel, nicht das Zeichnen -
        // die letzte Zeile ueberhaupt ist immer ein letztes Kind, und eine
        // Zeile mit einem Geschwister danach ist es nie.
        {
            expect("Baum: letzte Zeile ist letztes Kind",
                   !open_.empty() && open_.back().lastChild, true);
            bool ok = true;
            for (std::size_t i = 0; i + 1 < open_.size(); ++i) {
                if (open_[i].depth != open_[i + 1].depth) { continue; }
                // Gleiche Ebene direkt danach: dann war es NICHT das letzte.
                if (open_[i].lastChild) { ok = false; break; }
            }
            expect("Baum: Zeile mit Geschwister danach ist nicht letztes Kind",
                   ok, true);
        }

