        expect("Baum: zugeklappt bleiben Makro und Block", folded.size() == 2, true);
        expect("Baum: aufgeklappt kommen drei Zeilen dazu",
               open_.size() - folded.size() == 3, true);
        expect("Baum: Makrozeile traegt I_MACRO",
               !folded.empty() && folded[0].icon == "I_MACRO", true);
        expect("Baum: Symbol kommt aus der .bhc",
               open_.size() > 1 && open_[1].icon == "I_SET", true);
        expect("Baum: gesperrtes Feld erkannt",
               open_.size() > 1 && open_[1].locked, true);
        expect("Baum: Blockbefehl hat Kinder",
               !open_.empty() && open_.back().depth == 1, true);

        // --- Zwei Spalten statt einer Beschriftung ------------------------
        //
        // Die Anzeige setzt Name und Argumente getrennt, damit die Klammern
        // untereinander stehen. text muss weiterhin genau Name + " " +
        // args sein, sonst laufen Anzeige und Ziehtext auseinander.
        {
            bool split = true;
            for (const bhed::Row& r : open_) {
                if (r.what != bhed::Row::What::Command) { continue; }
                if (r.name.empty() || r.args.empty()) { split = false; break; }
                if (r.text != r.name + " " + r.args) { split = false; break; }
            }
            expect("Baum: Name und Argumente getrennt, text bleibt gleich",
                   split, true);
            expect("Baum: Argumente beginnen mit der Klammer",
                   open_.size() > 1 && !open_[1].args.empty() &&
                       open_[1].args.front() == '(',
                   true);
        }

