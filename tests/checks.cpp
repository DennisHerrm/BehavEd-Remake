    // --- argForParam mit GEAENDERTEM Wert --------------------------------
    //
    // Der Rundgang ueber den Bestand (edittour) aendert nie etwas und deckt
    // deshalb nur die Regel "unveraendert bleibt unveraendert" ab. Eine
    // Mutationsprobe hat gezeigt, dass die beiden anderen Regeln dabei
    // voellig ungeprueft blieben. Hier stehen sie.
    {
        using bhed::Arg;
        using bhed::Param;

        auto param = [](Param::Kind k, const char* ts = "") {
            Param p;
            p.kind = k;
            p.typeset = ts;
            return p;
        };
        auto arg = [](Arg::Kind k, const char* text, const char* ts = "") {
            Arg a;
            a.kind = k;
            a.text = text;
            a.typeset = ts;
            return a;
        };

        // Stand ein Ausdruck drin, bleibt es einer - auch in einem %v-Feld.
        //     set ( "SET_ORIGIN", $tag( "press1", ORIGIN)$ )
        const Arg wasExpr = arg(Arg::Kind::Expr, "tag( \"a\", ORIGIN)");
        const Arg r1 = bhed::argForParam(param(Param::Kind::Vector),
                                         "tag( \"b\", ORIGIN)", g_db, &wasExpr);
        expect("argForParam: Ausdruck bleibt Ausdruck, auch im Vektorfeld",
               r1.kind == Arg::Kind::Expr, true);

        // In einem Ausdrucksfeld bleibt eine blanke Zahl blank.
        //     move ( $tag( "cp1", ORIGIN)$, 0.000 )
        const Arg wasNumber = arg(Arg::Kind::Number, "0.000");
        const Arg r2 = bhed::argForParam(param(Param::Kind::Expr), "1.500",
                                         g_db, &wasNumber);
        expect("argForParam: blanke Zahl im Ausdrucksfeld bleibt blank",
               r2.kind == Arg::Kind::Number, true);

        // ... und ein $2$ bleibt ein $2$.
        const Arg wasDollar = arg(Arg::Kind::Expr, "2");
        const Arg r3 = bhed::argForParam(param(Param::Kind::Expr), "3",
                                         g_db, &wasDollar);
        expect("argForParam: $2$ bleibt Ausdrucksform", r3.kind == Arg::Kind::Expr, true);

        // Geaenderter Wert in einem Auswahlfeld bekommt die Annotation.
        const Arg wasPlain = arg(Arg::Kind::String, "SET_WALKING");
        const Arg r4 = bhed::argForParam(param(Param::Kind::TypeSet, "SET_TYPES"),
                                         "SET_RUNNING", g_db, &wasPlain);
        expect("argForParam: geaenderter Auswahlwert bekommt /*@TYPMENGE*/",
               r4.typeset == "SET_TYPES", true);

        // Unveraendert: keine Annotation anhaengen (Makroausklappungen).
        const Arg r5 = bhed::argForParam(param(Param::Kind::TypeSet, "SET_TYPES"),
                                         "SET_WALKING", g_db, &wasPlain);
        expect("argForParam: unveraenderter Wert behaelt fehlende Annotation",
               r5.typeset.empty(), true);

        // %i-Typmenge steht blank, %s in Anfuehrungszeichen.
        const Arg r6 = bhed::argForParam(param(Param::Kind::TypeSet, "AFFECT_TYPE"),
                                         "INSERT", g_db, nullptr);
        expect("argForParam: %i-Typmenge blank", r6.kind == Arg::Kind::Ident, true);
        const Arg r7 = bhed::argForParam(param(Param::Kind::TypeSet, "SET_TYPES"),
                                         "SET_HEALTH", g_db, nullptr);
        expect("argForParam: %s-Typmenge zitiert", r7.kind == Arg::Kind::String, true);

        // Gesperrtes Feld bleibt gesperrt.
        Arg locked = arg(Arg::Kind::String, "true");
        locked.locked = true;
        const Arg r8 = bhed::argForParam(param(Param::Kind::String), "false",
                                         g_db, &locked);
        expect("argForParam: /*!*/ bleibt erhalten", r8.locked, true);
    }

