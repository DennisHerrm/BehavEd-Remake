        // Zugeklappt gegen aufgeklappt. Der Schalter dafuer ist der
        // Aufklappzustand, nicht foldMacros - letzterer bestimmt nur, OB
        // die Befehle ueberhaupt Kinder des Makros werden.
        bhed::TreeOptions o;
        bhed::Expanded closed;
        o.expanded = &closed;
        std::vector<bhed::Row> folded;
        bhed::buildTree(sc, g_db, o, folded);

