        gf.gFloats = true;
        std::vector<bhed::Row> withG;
        bhed::buildTree(sc, g_db, gf, withG);
        bool trimmed = false;
        for (const auto& r : withG)
            if (r.text.find("wait ( 1000 )") != std::string::npos) trimmed = true;
        expect("Baum: %g floats kuerzt 1000.000 auf 1000", trimmed, true);
