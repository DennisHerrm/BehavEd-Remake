// Probe fuer bhed/npcklasse.h (rc602): welcher NPC_type aus welchem
// Klassennamen kommt (SP_NPC_* in NPC_spawn.cpp, OpenJK und Movie Duels),
// und dass die Szene die Figuren der Karte damit baut.
//
// Gemeldet (md_am_sith): "der NPC droid fehlt" - ein NPC_Droid_R2D2 ohne
// NPC_type-Schluessel und ohne Namen. Im Spiel setzt SP_NPC_Droid_R2D2 den
// Typ "r2d2" und spawnt die Figur beim Laden der Karte.
#include "bhed/npcklasse.h"
#include "bhed/scene.h"

#include <cstdio>
#include <string>
#include <vector>

using namespace bhed;

namespace {
int g_fehler = 0;
void pruefe(bool ok, const std::string& was) {
    std::printf("%s %s\n", ok ? "OK    " : "FEHLER", was.c_str());
    if (!ok) { ++g_fehler; }
}
std::string typ(const char* klasse, int sf = 0, const char* schluessel = "", bool md = true, bool msg = false) {
    return npcKlassenTyp(klasse, sf, schluessel, msg, md).typ;
}
MapData karte(const char* text) {
    MapData m;
    parseEntities(text, m.entities);
    return m;
}
Scene szene(const std::string& body, const MapData& m, bool kartenFiguren) {
    Script s;
    std::vector<Diag> d;
    (void)readScript("//Generated by BehavEd\r\n" + body, s, d);
    SzenenHilfe h;
    h.kartenFiguren = kartenFiguren;
    return buildScene(s, m, &h);
}
const Actor* figur(const Scene& s, const std::string& name) {
    for (const Actor& a : s.actors) {
        if (a.name == name) { return &a; }
    }
    return nullptr;
}
}  // namespace

int main() {
    // --- Die Tabelle ------------------------------------------------------
    pruefe(typ("NPC_Droid_R2D2") == "r2d2", "NPC_Droid_R2D2 -> r2d2 (SP_NPC_Droid_R2D2)");
    pruefe(typ("NPC_Droid_R2D2", 1) == "r2d2_imp", "NPC_Droid_R2D2 spawnflags 1 -> r2d2_imp");
    pruefe(typ("NPC_Droid_R2D2", 0, "gonk") == "r2d2", "NPC_Droid_R2D2 ueberschreibt einen NPC_type-Schluessel");
    pruefe(typ("NPC_Reborn", 0, "md_maul") == "md_maul", "NPC_Reborn: der Schluessel geht vor (if !NPC_type)");
    pruefe(typ("NPC_Reborn", 2) == "rebornfencer", "NPC_Reborn spawnflags 2 -> rebornfencer");
    pruefe(typ("NPC_Reborn", 3) == "rebornforceuser", "NPC_Reborn 1 vor 2 (Reihenfolge der Engine)");
    pruefe(typ("NPC_Stormtrooper", 12) == "rockettrooper", "NPC_Stormtrooper 8 vor 4");
    pruefe(typ("NPC_StormtrooperOfficer") == "stofficer", "NPC_StormtrooperOfficer -> spawnflags|1 -> stofficer");
    {
        const NpcKlassenTyp k = npcKlassenTyp("NPC_Stormtrooper", 0, "", false, true);
        pruefe(k.typ == "StormTrooper" && k.zufall.size() == 2 && k.zufall[1] == "StormTrooper2",
               "NPC_Stormtrooper ohne Flags: Zufall StormTrooper/StormTrooper2, Vorschau die erste");
    }
    pruefe(typ("NPC_Jedi", 4) == "jedi_hf1" && npcKlassenTyp("NPC_Jedi", 4, "", false, true).zufall.size() == 12,
           "NPC_Jedi RANDOM: 12 Moeglichkeiten");
    pruefe(typ("NPC_Jedi", 2) == "jedimaster" && typ("NPC_Jedi", 1) == "jeditrainer", "NPC_Jedi 2/1");
    pruefe(typ("NPC_Human_Merc", 1, "", true, true) == "human_merc_key", "NPC_Human_Merc: message vor den Flags");
    pruefe(typ("NPC_Reborn_New", 8 | 2) == "RebornMasterStaff" && typ("NPC_Reborn_New", 4) == "reborn_new2",
           "NPC_Reborn_New Meister/Stufe 2");
    pruefe(typ("NPC_Cultist_Saber", 4) == "cultist_saber" && typ("NPC_Cultist_Saber", 4 | 8) == "cultist_saber_throw",
           "NPC_Cultist_Saber ALL ist unerreichbar (doppelte Pruefung auf 2 in der Engine)");
    pruefe(typ("NPC_Cultist_Saber_Powers", 8) == "cultist_saber_throw", "_Powers THROW ohne 2");
    pruefe(typ("NPC_Droid_Remote") == "remote_sp", "NPC_Droid_Remote -> remote_sp");
    pruefe(typ("NPC_Colombian_EmplacedGunner") == "ShadowTrooper", "Colombian_EmplacedGunner -> SP_NPC_ShadowTrooper");
    pruefe(typ("NPC_Manuel_Vergara_RMG") == "Desann", "Manuel_Vergara_RMG -> SP_NPC_Desann");
    pruefe(typ("NPC_Vehicle") == "swoop" && typ("NPC_Vehicle", 0, "atst_vehicle") == "atst_vehicle", "NPC_Vehicle");
    pruefe(typ("NPC_spawner") == "" && typ("NPC_spawner", 0, "md_x") == "md_x", "NPC_spawner: nur der Schluessel");
    // Regelwerke
    pruefe(typ("NPC_Galak", 1, "", true) == "Galak_Mech", "Movie Duels: NPC_Galak 1 -> Galak_Mech");
    {
        const NpcKlassenTyp k = npcKlassenTyp("NPC_Galak", 0, "", false, false);
        pruefe(k.bekannt && !k.spawnt && k.typ.empty(), "OpenJK: SP_NPC_Galak ist leer - niemand erscheint");
    }
    pruefe(typ("NPC_md_darkside_sith1_random", 0, "", true) == "md_dooku" &&
               npcKlassenTyp("NPC_md_darkside_sith1_random", 0, "", false, true).zufall.size() == 33,
           "Movie Duels: NPC_md_darkside_sith1_random (33 Namen, Q_irand2(0, 32))");
    pruefe(npcKlassenTyp("NPC_md_lightside_jedi1_random", 0, "", false, true).zufall.size() == 49 &&
               npcKlassenTyp("NPC_md_lightside_jedi2_random", 0, "", false, true).zufall.size() == 47 &&
               npcKlassenTyp("NPC_md_lightside_gunners_random", 0, "", false, true).zufall.size() == 38,
           "Movie Duels: Zufallslisten so lang wie Q_irand2 zieht");
    pruefe(!npcKlassenTyp("NPC_md_darkside_sith1_random", 0, "", false, false).bekannt,
           "OpenJK kennt die md-Zufallsspawner nicht");
    pruefe(typ("NPC_Projection_far", 0, "", true) == "projection_far" &&
               !npcKlassenTyp("NPC_Projection_far", 0, "", false, false).bekannt,
           "NPC_Projection_* nur in Movie Duels");
    pruefe(!npcKlassenTyp("NPC_Gibtsnicht", 0, "", false, true).bekannt && typ("NPC_Gibtsnicht").empty(),
           "unbekannte Klasse: keine Spawnfunktion, kein Typ");
    pruefe(!npcKlassenTyp("npc_droid_r2d2", 0, "", false, true).bekannt, "Klassennamen genau (strcmp)");

    // --- Entities ---------------------------------------------------------
    const MapData m = karte(
        "{\n\"classname\" \"NPC_Droid_R2D2\"\n\"origin\" \"340 6932 24\"\n\"angle\" \"225\"\n}\n"
        "{\n\"classname\" \"NPC_spawner\"\n\"npc_targetname\" \"ani1\"\n\"npc_type\" \"md_ani_ep3_robed\"\n"
        "\"origin\" \"336 6872 24\"\n\"angle\" \"270\"\n}\n"
        "{\n\"classname\" \"NPC_Stormtrooper\"\n\"npc_targetname\" \"st1\"\n\"NPC_type\" \"md_clo_rex\"\n"
        "\"origin\" \"0 0 0\"\n}\n"
        "{\n\"classname\" \"NPC_spawner\"\n\"targetname\" \"spaeter\"\n\"npc_targetname\" \"bd1\"\n"
        "\"npc_type\" \"battledroid\"\n\"origin\" \"64 0 0\"\n}\n"
        "{\n\"classname\" \"NPC_Gibtsnicht\"\n\"origin\" \"128 0 0\"\n}\n");
    pruefe(effektiverNpcTyp(m.entities[0]) == "r2d2", "Entity NPC_Droid_R2D2 ohne Schluessel -> r2d2");
    pruefe(npcSpawntBeimKartenstart(m.entities[0]), "NPC_Droid_R2D2 ohne targetname spawnt beim Kartenstart");
    pruefe(!npcSpawntBeimKartenstart(m.entities[3]), "Spawner mit targetname wartet auf use");
    pruefe(!npcSpawntBeimKartenstart(m.entities[4]), "unbekannte Klasse spawnt nicht");

    // --- Die Szene --------------------------------------------------------
    const std::string skript =
        "affect ( \"ani1\", FLUSH )\r\n{\r\n\twait ( 500.000 );\r\n}\r\n"
        "affect ( \"st1\", FLUSH )\r\n{\r\n\twait ( 500.000 );\r\n}\r\n";
    {
        const Scene s = szene(skript, m, true);
        const Actor* st = figur(s, "st1");
        pruefe(st != nullptr && st->npcType == "StormTrooper",
               "Szene: affect auf NPC_Stormtrooper -> StormTrooper (die Klasse ueberschreibt NPC_type)");
        const Actor* droid = figur(s, "NPC_Droid_R2D2#0");
        pruefe(droid != nullptr && droid->npcType == "r2d2" && droid->kartenFigur && droid->kartenEntity == 0,
               "Szene: der Droide ohne Namen steht als Kartenfigur da (r2d2)");
        pruefe(droid != nullptr && droid->haveStart && droid->start[0] == 340.0F && droid->startAngles[1] == 225.0F,
               "Szene: Kartenfigur am Ort und mit Blick des Spawners");
        pruefe(figur(s, "bd1") == nullptr, "Szene: Spawner mit targetname erscheint nicht von selbst");
        int n = 0;
        for (const Actor& a : s.actors) { n += a.name == "ani1" ? 1 : 0; }
        pruefe(n == 1, "Szene: ani1 nur einmal (affect und Kartenstart)");
        pruefe(s.actors.size() == 3, "Szene: ani1, st1, Droide - " + std::to_string(s.actors.size()) + " Figuren");
    }
    {
        const Scene s = szene(skript, m, false);
        pruefe(s.actors.size() == 2, "Szene ohne kartenFiguren: nur die Figuren der Skripte");
    }
    std::printf("%s (%d Fehler)\n", g_fehler == 0 ? "npcklasse: alles gut" : "npcklasse: FEHLER", g_fehler);
    return g_fehler == 0 ? 0 : 1;
}
