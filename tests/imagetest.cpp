    // --- Der Schluessel der Bildtabelle ---------------------------------
    //
    // Seit rc187 werden entzifferte Bilder nach Namen gemerkt: von 6,2 s
    // beim Laden einer Mission gingen 5,0 s in das Entpacken und
    // Entziffern derselben Texturen, immer wieder, je Modell und je
    // Flaeche.
    //
    // Der Schluessel ist der ganze Gewinn - stimmt er nicht, treffen zwei
    // Namen desselben Bildes nicht aufeinander, und der Zwischenspeicher
