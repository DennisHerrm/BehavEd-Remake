int fails = 0;
void expect(const char* what, bool ok) {
    std::printf("  %s  %s\n", ok ? "ok  " : "FEHL", what);
    if (!ok) { ++fails; }
}

// Ein unkomprimiertes TGA, 24 Bit.
std::vector<unsigned char> makeTga(int w, int h) {
    std::vector<unsigned char> b(18, 0);
    b[2] = 2;                                        // unkomprimiert, RGB
    b[12] = static_cast<unsigned char>(w & 0xFF);
    b[13] = static_cast<unsigned char>(w >> 8);
    b[14] = static_cast<unsigned char>(h & 0xFF);
    b[15] = static_cast<unsigned char>(h >> 8);
    b[16] = 24;
    for (int y = 0; y < h; ++y) {
        for (int x = 0; x < w; ++x) {
            b.push_back(static_cast<unsigned char>(x * 3));   // B
            b.push_back(static_cast<unsigned char>(y * 5));   // G
            b.push_back(static_cast<unsigned char>(200));     // R
        }
    }
    return b;
}
