        // --- Die beiden Faktoren von glBlendFunc, einzeln ----------------
        //
        // BlendMode hat fuenf Schubladen; in den sechs pk3 stehen aber
        // VIERZEHN verschiedene Kombinationen auf Zusatzstufen. Deshalb
        // werden die Faktoren jetzt einzeln gemerkt und gerechnet.
