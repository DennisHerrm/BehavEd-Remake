        // 0.5, die Engine ist bei sin(45 Grad) = 0.707 schon weiter.
        const float mitte = bhed::nonlinearStop(0.5F);
        std::printf("     bei der Haelfte: %.3f (gleichmaessig waere 0.5)\n",
                    (double)mitte);
        expect("in der Mitte schon ueber der Haelfte", mitte > 0.70F);
        expect("und nicht darueber hinaus", mitte < 0.71F);

