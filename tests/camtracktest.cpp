// camtracktest.cpp - die Kamerabahn
//
// Alles hier ist an cg_camera.cpp nachgemessen. Die Proben pruefen genau
// die Stellen, an denen man es falsch machen wuerde, wenn man es annimmt
// statt nachzusehen.
#include "bhed/camtrack.h"
#include "bhed/mapview.h"
